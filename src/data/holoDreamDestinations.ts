export function localizeHotCityLabel(city: string, locale: 'zh' | 'en'): string {
  if (locale === 'en') {
    return HOT_CITY_LABEL_EN[city] ?? city;
  }
  return city;
}

function uniquePreserveOrder(list: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const city of list) {
    if (seen.has(city)) continue;
    seen.add(city);
    out.push(city);
  }
  return out;
}

